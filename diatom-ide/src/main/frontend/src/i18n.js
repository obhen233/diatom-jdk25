const currentLang = ref(localStorage.getItem('ide-lang') || 'en')

// 监听 App.vue 触发的语言变更事件
if (typeof window !== 'undefined') {
  window.addEventListener('lang-change', (e) => {
    const lang = e.detail || 'en'
    if (messages[lang]) {
      currentLang.value = lang
    }
  })
}

function t(key, params) {
  const lang = messages[currentLang.value] || messages.en
  // Support nested keys like 'vcsSidebar.title'
  let text = key.split('.').reduce((obj, k) => (obj || {})[k], lang) || messages.en[key.split('.').reduce((obj, k) => (obj || {})[k], messages.en)] || key
  if (params) {
    Object.keys(params).forEach(k => {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k])
    })
  }
  return text
}

function setLang(lang) {
  if (messages[lang]) {
    currentLang.value = lang
    localStorage.setItem('ide-lang', lang)
    langChangeCallbacks.forEach(cb => cb(lang))
  }
}

const langChangeCallbacks = []

function onLangChange(cb) {
  langChangeCallbacks.push(cb)
  return () => { const i = langChangeCallbacks.indexOf(cb); if (i >= 0) langChangeCallbacks.splice(i, 1) }
}

function getLang() {
  return currentLang.value
}

function getAvailableLangs() {
  return Object.keys(messages)
}

export { t, setLang, getLang, getAvailableLangs, currentLang, onLangChange }
